function cityConfig(id, name, metar, lat, lon, timezone, modelOptions, badge) {
  return {
    id,
    name,
    metar,
    airport: `${name} airport (${metar})`,
    timezone,
    coords: { lat, lon },
    omKind: 'hourly',
    omBadge: badge || 'OM',
    omSourceLabel: 'Open-Meteo Forecast',
    modelOptions,
  };
}

